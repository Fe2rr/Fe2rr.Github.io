/*
 * Generate devices-seed.sql from a local AndroidDeviceNames JSON export.
 *
 * Usage:
 *   node scripts/migrate-devices.mjs ./devices.json
 *
 * Accepted input: an array of objects with id and name fields.
 * This script does not fetch or assume a third-party source URL.
 */
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

function sqlString(value) {
    return `'${String(value ?? "").replace(/'/g, "''")}'`;
}

async function main() {
    const inputPath = process.argv[2];
    if (!inputPath) {
        throw new Error("Pass the path to a local devices JSON file.");
    }

    const parsed = JSON.parse(await fs.readFile(path.resolve(inputPath), "utf8"));
    const source = Array.isArray(parsed) ? parsed : parsed?.devices;
    if (!Array.isArray(source)) {
        throw new Error("Expected a JSON array or an object containing a devices array.");
    }

    const devices = new Map();
    for (const item of source) {
        const id = String(item?.id || "").trim();
        const name = String(item?.name || "").trim();
        if (id && name) devices.set(id, name);
    }

    if (!devices.size) {
        throw new Error("No valid devices found; refusing to generate an empty seed.");
    }

    const lines = [
        "-- Generated by scripts/migrate-devices.mjs",
        "INSERT INTO devices (id, name) VALUES",
        ...Array.from(devices, ([id, name]) => `(${sqlString(id)}, ${sqlString(name)})`).map(
            (value, index, values) => value + (index === values.length - 1 ? "" : ",")
        ),
        "ON CONFLICT(id) DO UPDATE SET name = excluded.name;",
        ""
    ];

    const outputPath = path.resolve(__dirname, "..", "devices-seed.sql");
    await fs.writeFile(outputPath, lines.join("\n"), "utf8");
    console.log(`Generated ${outputPath} with ${devices.size} devices.`);
}

main().catch((error) => {
    console.error("Device migration failed:", error);
    process.exit(1);
});
