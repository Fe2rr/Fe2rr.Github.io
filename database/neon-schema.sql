-- NAPL community data schema for Neon PostgreSQL.
-- Preserve all legacy identifiers, hashes, counters and timestamps.
CREATE TABLE IF NOT EXISTS devices (
  id text PRIMARY KEY CHECK (length(id) BETWEEN 1 AND 200),
  name text NOT NULL CHECK (length(name) BETWEEN 1 AND 240),
  manufacturer text NOT NULL DEFAULT '',
  model text NOT NULL DEFAULT '',
  soc text NOT NULL DEFAULT '',
  device_type text NOT NULL DEFAULT 'phone'
);
CREATE TABLE IF NOT EXISTS rating_tokens (
  token_hash text PRIMARY KEY CHECK (length(token_hash)=64),
  ip_hash text NOT NULL CHECK (length(ip_hash)=64),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS rating_token_issues (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  ip_hash text NOT NULL CHECK (length(ip_hash)=64),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS rating_votes (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  port_id text NOT NULL CHECK (length(port_id) BETWEEN 1 AND 120),
  token_hash text NOT NULL CHECK (length(token_hash)=64),
  stars smallint NOT NULL CHECK (stars BETWEEN 1 AND 5),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(port_id, token_hash)
);
CREATE TABLE IF NOT EXISTS game_popularity (
  game_key text PRIMARY KEY,
  all_time_visits bigint NOT NULL DEFAULT 0 CHECK (all_time_visits>=0),
  week_visits bigint NOT NULL DEFAULT 0 CHECK (week_visits>=0),
  month_visits bigint NOT NULL DEFAULT 0 CHECK (month_visits>=0),
  week_start date NOT NULL DEFAULT date_trunc('week',now())::date,
  month_start date NOT NULL DEFAULT date_trunc('month',now())::date,
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS game_popularity_visit_limits (
  ip_hash text NOT NULL,
  game_key text NOT NULL,
  last_visit_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(ip_hash,game_key)
);
CREATE TABLE IF NOT EXISTS compatibility_reports (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  port_id text NOT NULL CHECK (length(port_id) BETWEEN 1 AND 120),
  token_hash text NOT NULL CHECK (length(token_hash)=64),
  device_id text NOT NULL REFERENCES devices(id),
  device_name text NOT NULL CHECK (length(device_name) BETWEEN 1 AND 240),
  works boolean NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now(),
  status text NOT NULL DEFAULT 'crash' CHECK (status IN ('crash','low_fps','playable_30','playable_60')),
  UNIQUE(port_id,token_hash,device_id)
);
CREATE TABLE IF NOT EXISTS link_reports (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  port_id text NOT NULL CHECK (length(port_id) BETWEEN 1 AND 120),
  reporter_hash text NOT NULL,
  reason text NOT NULL CHECK (length(reason) BETWEEN 1 AND 120),
  url text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  note text NOT NULL DEFAULT '',
  UNIQUE(port_id,reporter_hash)
);
CREATE TABLE IF NOT EXISTS link_report_rate_limits (
  reporter_hash text PRIMARY KEY,
  last_report_at timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS rating_votes_port_idx ON rating_votes(port_id);
CREATE INDEX IF NOT EXISTS rating_votes_token_time_idx ON rating_votes(token_hash,created_at);
CREATE INDEX IF NOT EXISTS compatibility_port_time_idx ON compatibility_reports(port_id,updated_at DESC,id DESC);
CREATE INDEX IF NOT EXISTS compatibility_device_idx ON compatibility_reports(device_id);
CREATE INDEX IF NOT EXISTS devices_soc_idx ON devices(lower(soc));
CREATE INDEX IF NOT EXISTS link_reports_port_idx ON link_reports(port_id,updated_at DESC);
CREATE INDEX IF NOT EXISTS popularity_rank_week_idx ON game_popularity(week_visits DESC);
CREATE INDEX IF NOT EXISTS popularity_rank_month_idx ON game_popularity(month_visits DESC);
CREATE INDEX IF NOT EXISTS popularity_rank_all_idx ON game_popularity(all_time_visits DESC);

CREATE OR REPLACE FUNCTION napl_register_game_visit(p_game_key text,p_ip_hash text)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path TO public AS $
DECLARE v_now timestamptz:=now(); v_week date:=date_trunc('week',now())::date;
v_month date:=date_trunc('month',now())::date; v_allowed text;
BEGIN
 IF p_game_key IS NULL OR length(p_game_key) NOT BETWEEN 1 AND 180 OR p_game_key !~ '^[a-z0-9][a-z0-9-]*$' OR p_ip_hash IS NULL OR length(p_ip_hash)<>64 THEN RAISE EXCEPTION 'invalid_request'; END IF;
 INSERT INTO game_popularity_visit_limits(ip_hash,game_key,last_visit_at) VALUES(p_ip_hash,p_game_key,v_now)
 ON CONFLICT(ip_hash,game_key) DO UPDATE SET last_visit_at=excluded.last_visit_at
 WHERE game_popularity_visit_limits.last_visit_at < v_now-interval '20 seconds' RETURNING game_key INTO v_allowed;
 IF v_allowed IS NULL THEN RETURN false; END IF;
 INSERT INTO game_popularity(game_key,all_time_visits,week_visits,month_visits,week_start,month_start,updated_at)
 VALUES(p_game_key,1,1,1,v_week,v_month,v_now)
 ON CONFLICT(game_key) DO UPDATE SET all_time_visits=game_popularity.all_time_visits+1,
 week_visits=CASE WHEN game_popularity.week_start=v_week THEN game_popularity.week_visits+1 ELSE 1 END,
 month_visits=CASE WHEN game_popularity.month_start=v_month THEN game_popularity.month_visits+1 ELSE 1 END,
 week_start=v_week,month_start=v_month,updated_at=v_now;
 RETURN true;
END $$;

CREATE OR REPLACE FUNCTION napl_get_popularity(p_period text DEFAULT 'week')
RETURNS TABLE(slug text,visits bigint) LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO public AS $
 SELECT game_key,CASE WHEN lower(coalesce(p_period,'week'))='alltime' THEN all_time_visits
 WHEN lower(coalesce(p_period,'week'))='month' THEN CASE WHEN month_start=date_trunc('month',now())::date THEN month_visits ELSE 0 END
 ELSE CASE WHEN week_start=date_trunc('week',now())::date THEN week_visits ELSE 0 END END
 FROM game_popularity
 WHERE CASE WHEN lower(coalesce(p_period,'week'))='alltime' THEN all_time_visits>0
 WHEN lower(coalesce(p_period,'week'))='month' THEN month_start=date_trunc('month',now())::date AND month_visits>0
 ELSE week_start=date_trunc('week',now())::date AND week_visits>0 END
 ORDER BY 2 DESC,1 ASC
$$;

CREATE OR REPLACE FUNCTION napl_issue_rating_token(p_ip_hash text,p_token_hash text)
RETURNS boolean LANGUAGE plpgsql AS $$
DECLARE n integer;
BEGIN
 IF length(coalesce(p_ip_hash,''))<>64 OR length(coalesce(p_token_hash,''))<>64 THEN RAISE EXCEPTION 'invalid_token_issue'; END IF;
 PERFORM pg_advisory_xact_lock(hashtextextended(p_ip_hash,1));
 DELETE FROM rating_token_issues WHERE created_at<now()-interval '24 hours';
 SELECT count(*) INTO n FROM rating_token_issues WHERE ip_hash=p_ip_hash AND created_at>now()-interval '1 hour';
 IF n>=10 THEN RETURN false; END IF;
 INSERT INTO rating_token_issues(ip_hash) VALUES(p_ip_hash);
 INSERT INTO rating_tokens(token_hash,ip_hash) VALUES(p_token_hash,p_ip_hash) ON CONFLICT DO NOTHING;
 RETURN true;
END $$;

CREATE OR REPLACE FUNCTION napl_submit_vote(p_port_id text,p_token_hash text,p_stars smallint)
RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE n integer; existed boolean;
BEGIN
 IF length(coalesce(p_port_id,'')) NOT BETWEEN 1 AND 120 OR length(coalesce(p_token_hash,''))<>64 OR p_stars IS NULL OR p_stars NOT BETWEEN 1 AND 5 THEN RAISE EXCEPTION 'invalid_vote'; END IF;
 PERFORM pg_advisory_xact_lock(hashtextextended(p_token_hash,0));
 SELECT EXISTS(SELECT 1 FROM rating_votes WHERE port_id=p_port_id AND token_hash=p_token_hash) INTO existed;
 IF NOT existed THEN
  SELECT count(*) INTO n FROM rating_votes WHERE token_hash=p_token_hash AND created_at>now()-interval '1 hour';
  IF n>=20 THEN RAISE EXCEPTION 'rate_limited'; END IF;
 END IF;
 INSERT INTO rating_votes(port_id,token_hash,stars) VALUES(p_port_id,p_token_hash,p_stars)
 ON CONFLICT(port_id,token_hash) DO UPDATE SET stars=excluded.stars,updated_at=now();
 RETURN jsonb_build_object('ok',true,'port_id',p_port_id,'stars',p_stars);
END $$;

CREATE OR REPLACE FUNCTION napl_get_my_votes(p_token_hash text)
RETURNS jsonb LANGUAGE sql STABLE AS $$
 SELECT coalesce(jsonb_object_agg(port_id,stars),'{}'::jsonb) FROM rating_votes WHERE token_hash=p_token_hash
$$;
CREATE OR REPLACE FUNCTION napl_is_valid_rating_token(p_token_hash text)
RETURNS boolean LANGUAGE sql STABLE AS $$
 SELECT EXISTS(SELECT 1 FROM rating_tokens WHERE token_hash=p_token_hash) OR EXISTS(SELECT 1 FROM rating_votes WHERE token_hash=p_token_hash)
$$;
CREATE OR REPLACE FUNCTION napl_get_ratings()
RETURNS jsonb LANGUAGE sql STABLE AS $$
 WITH g AS (SELECT coalesce(avg(stars),0)::numeric global_avg FROM rating_votes),
 p AS (SELECT port_id,count(*)::int votes,avg(stars)::numeric avg FROM rating_votes GROUP BY port_id)
 SELECT jsonb_build_object('ports',coalesce((SELECT jsonb_agg(jsonb_build_object('port_id',p.port_id,'votes',p.votes,'avg',round(p.avg,2),'score',round((p.votes::numeric/(p.votes+5))*p.avg+(5::numeric/(p.votes+5))*g.global_avg,2)) ORDER BY p.port_id) FROM p CROSS JOIN g),'[]'::jsonb),'global_avg',(SELECT round(global_avg,2) FROM g))
$$;

CREATE OR REPLACE FUNCTION napl_reserve_link_report(p_reporter_hash text)
RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE ok boolean; retry integer;
BEGIN
 INSERT INTO link_report_rate_limits(reporter_hash,last_report_at) VALUES(p_reporter_hash,now())
 ON CONFLICT(reporter_hash) DO UPDATE SET last_report_at=excluded.last_report_at
 WHERE link_report_rate_limits.last_report_at<=now()-interval '10 minutes' RETURNING true INTO ok;
 IF coalesce(ok,false) THEN RETURN jsonb_build_object('allowed',true,'retry_after_seconds',0); END IF;
 SELECT greatest(1,ceil(extract(epoch FROM(last_report_at+interval '10 minutes'-now())))::int) INTO retry FROM link_report_rate_limits WHERE reporter_hash=p_reporter_hash;
 RETURN jsonb_build_object('allowed',false,'retry_after_seconds',coalesce(retry,600));
END $$;

CREATE OR REPLACE FUNCTION get_compatibility_devices()
RETURNS jsonb LANGUAGE sql STABLE AS $$
 SELECT coalesce(jsonb_agg(jsonb_build_object('id',id,'name',name,'manufacturer',manufacturer,'model',model,'soc',soc,'deviceType',device_type) ORDER BY name COLLATE "C"),'[]'::jsonb)
 FROM devices WHERE nullif(btrim(manufacturer),'') IS NOT NULL AND nullif(btrim(model),'') IS NOT NULL AND nullif(btrim(soc),'') IS NOT NULL
$$;
CREATE OR REPLACE FUNCTION get_compatibility_for_ports(p_port_ids text[])
RETURNS jsonb LANGUAGE sql STABLE AS $$
 SELECT coalesce(jsonb_object_agg(req.port_id,jsonb_build_object('yes',s.yes,'no',s.no,'counts',jsonb_build_object('playable_60',s.p60,'playable_30',s.p30,'low_fps',s.low,'crash',s.crash),'reports',r.reports)),'{}'::jsonb)
 FROM (SELECT DISTINCT unnest(coalesce(p_port_ids,ARRAY[]::text[])) port_id) req
 CROSS JOIN LATERAL (SELECT count(*) FILTER(WHERE status IN('playable_30','playable_60'))::int yes,count(*) FILTER(WHERE status IN('crash','low_fps'))::int no,count(*) FILTER(WHERE status='playable_60')::int p60,count(*) FILTER(WHERE status='playable_30')::int p30,count(*) FILTER(WHERE status='low_fps')::int low,count(*) FILTER(WHERE status='crash')::int crash FROM compatibility_reports WHERE port_id=req.port_id) s
 CROSS JOIN LATERAL (SELECT coalesce(jsonb_agg(jsonb_build_object('deviceId',x.device_id,'deviceName',coalesce(nullif(d.model,''),x.device_name),'deviceSoc',coalesce(d.soc,''),'deviceType',coalesce(nullif(d.device_type,''),'phone'),'status',x.status,'works',x.status IN('playable_30','playable_60'),'updatedAt',x.updated_at) ORDER BY x.updated_at DESC,x.id DESC),'[]'::jsonb) reports FROM (SELECT * FROM compatibility_reports WHERE port_id=req.port_id ORDER BY updated_at DESC,id DESC LIMIT 30) x LEFT JOIN devices d ON d.id=x.device_id) r
$$;
CREATE OR REPLACE FUNCTION get_compatibility_by_hardware(p_device_id text DEFAULT NULL,p_soc text DEFAULT NULL,p_query text DEFAULT NULL,p_limit integer DEFAULT 500)
RETURNS jsonb LANGUAGE sql STABLE AS $$
 SELECT coalesce(jsonb_agg(jsonb_build_object('portId',x.port_id,'deviceId',x.device_id,'deviceName',coalesce(nullif(d.model,''),x.device_name),'deviceSoc',coalesce(d.soc,''),'deviceType',coalesce(nullif(d.device_type,''),'phone'),'status',x.status,'works',x.status IN('playable_30','playable_60'),'updatedAt',x.updated_at) ORDER BY x.updated_at DESC,x.id DESC),'[]'::jsonb)
 FROM (SELECT * FROM compatibility_reports WHERE (coalesce(p_device_id,'')<>'' AND device_id=p_device_id) OR (coalesce(p_soc,'')<>'' AND device_id IN(SELECT id FROM devices WHERE lower(soc)=lower(p_soc))) OR (coalesce(p_device_id,'')='' AND coalesce(p_soc,'')='' AND coalesce(p_query,'')<>'' AND (lower(device_name) LIKE '%'||lower(p_query)||'%' OR device_id IN(SELECT id FROM devices WHERE lower(model) LIKE '%'||lower(p_query)||'%' OR lower(soc) LIKE '%'||lower(p_query)||'%'))) ORDER BY updated_at DESC,id DESC LIMIT least(greatest(coalesce(p_limit,500),1),1000)) x LEFT JOIN devices d ON d.id=x.device_id
$$;
CREATE OR REPLACE FUNCTION upsert_compatibility_report(p_port_id text,p_token_hash text,p_device_id text,p_works boolean DEFAULT NULL,p_status text DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE d devices%ROWTYPE; saved compatibility_reports%ROWTYPE; s text;
BEGIN
 SELECT * INTO d FROM devices WHERE id=p_device_id;
 IF d.id IS NULL THEN RAISE EXCEPTION 'Invalid device ID'; END IF;
 s:=CASE WHEN p_status IN('crash','low_fps','playable_30','playable_60') THEN p_status WHEN p_works IS TRUE THEN 'playable_30' WHEN p_works IS FALSE THEN 'crash' ELSE NULL END;
 IF s IS NULL THEN RAISE EXCEPTION 'Invalid compatibility status'; END IF;
 INSERT INTO compatibility_reports(port_id,token_hash,device_id,device_name,works,status) VALUES(p_port_id,p_token_hash,p_device_id,d.name,s IN('playable_30','playable_60'),s)
 ON CONFLICT(port_id,token_hash,device_id) DO UPDATE SET device_name=excluded.device_name,works=excluded.works,status=excluded.status,updated_at=now() RETURNING * INTO saved;
 RETURN jsonb_build_object('report',jsonb_build_object('portId',saved.port_id,'deviceId',saved.device_id,'deviceName',coalesce(nullif(d.model,''),saved.device_name),'deviceSoc',coalesce(d.soc,''),'deviceType',coalesce(nullif(d.device_type,''),'phone'),'status',saved.status,'works',saved.works,'updatedAt',saved.updated_at),'summary',get_compatibility_for_ports(ARRAY[p_port_id])->p_port_id);
END $$;

CREATE OR REPLACE FUNCTION napl_remove_vote(p_port_id text,p_token_hash text)
RETURNS jsonb LANGUAGE plpgsql SET search_path TO public, pg_temp AS $$
BEGIN
 IF p_port_id IS NULL OR length(p_port_id)<1 OR length(p_port_id)>120
    OR p_token_hash IS NULL OR length(p_token_hash)<>64 THEN
  RAISE EXCEPTION 'invalid_vote' USING ERRCODE='22023';
 END IF;
 DELETE FROM public.rating_votes WHERE port_id=p_port_id AND token_hash=p_token_hash;
 RETURN jsonb_build_object('ok',true,'port_id',p_port_id);
END $$;
